import abc
from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field

class TokenUsage(BaseModel):
    """Schema for tracking token consumption for telemetry and cost analysis."""
    prompt_tokens: int = Field(default=0, description="Number of tokens in the prompt.")
    completion_tokens: int = Field(default=0, description="Number of tokens generated by the model.")
    total_tokens: int = Field(default=0, description="Total tokens used.")

class LLMRequest(BaseModel):
    """Unified request contract for all LLM providers."""
    messages: List[Dict[str, str]] = Field(..., description="List of message dicts with 'role' and 'content'.")
    model: str = Field(..., description="The name of the model to use.")
    temperature: float = Field(default=0.7, description="Sampling temperature.")
    max_tokens: Optional[int] = Field(default=None, description="Maximum number of tokens to generate.")
    response_format: Optional[Dict[str, str]] = Field(
        default=None, description="Optional format requirement, e.g., {'type': 'json_object'}."
    )
    provider_kwargs: Dict[str, Any] = Field(
        default_factory=dict, description="Additional provider-specific parameters (e.g., top_p, num_ctx for Ollama)."
    )

class LLMResponse(BaseModel):
    """Unified response contract from all LLM providers."""
    content: str = Field(..., description="The raw text response generated by the model.")
    reasoning_trace: Optional[str] = Field(default=None, description="Extracted reasoning process (e.g., from <think> tags).")
    usage: TokenUsage = Field(default_factory=TokenUsage, description="Token usage statistics.")
    model_used: str = Field(..., description="The actual model used for generation.")
    latency_ms: float = Field(default=0.0, description="Execution time in milliseconds.")

class ModelCapabilities(BaseModel):
    """Metadata about a model's capabilities."""
    name: str
    provider: str
    context_window: int
    supports_json: bool
    supports_streaming: bool

class LLMProvider(abc.ABC):
    """Abstract base class for all LLM execution engines."""

    @abc.abstractmethod
    async def generate(self, request: LLMRequest) -> LLMResponse:
        """Executes the request against the provider's API."""
        pass

    @abc.abstractmethod
    async def health_check(self) -> bool:
        """Verifies if the provider is currently accessible and operational."""
        pass

    @abc.abstractmethod
    async def list_models(self) -> List[ModelCapabilities]:
        """Returns a list of available models and their capabilities."""
        pass
